const DICTIONARIES: Record<Lang, Record<TranslationKey, string>> = { en, ru, kz };

export function translate(lang: Lang, key: TranslationKey, values?: Record<string, string | number>): string {
  const text: string = DICTIONARIES[lang][key];
  return text.replace(/\{(\w+)\}/g, (match, name: string) => values?.[name] == null ? match : String(values[name]));
}

export function parseLanguage(value: string | null | undefined): Lang | null {
  const normalized = value?.trim().toLowerCase();
  if (normalized === "en") return "en";
  if (normalized === "ru") return "ru";
  if (normalized === "kz" || normalized === "kk") return "kz";
  return null;
}

export function readLanguage(value: string | null): Lang {
  return parseLanguage(value) ?? DEFAULT_LANGUAGE;
}

const KNOWN_PATHS = new Set(["/", "/evaluator", "/portfolio", "/roadmap", "/universities", "/leaderboard", "/about", "/contacts", "/auth"]);

export function resolveLangPath(pathname: string): { to: string; lang: Lang } | null {
  const clean = pathname.replace(/\/+$/, "") || "/";
  const parts = clean.split("/").filter(Boolean);
  if (parts.length === 0) return null;
  const maybeLang = parseLanguage(parts[parts.length - 1]);
  if (!maybeLang) return null;
  const base = parts.length === 1 ? "/" : `/${parts.slice(0, -1).join("/")}`;
  return KNOWN_PATHS.has(base) ? { to: base, lang: maybeLang } : null;
}
