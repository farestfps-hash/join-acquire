export function translate(lang: Lang, key: TranslationKey, values?: Record<string, string | number>): string {
  const text: string = (lang === "ru" ? ru : en)[key];
  return text.replace(/\{(\w+)\}/g, (match, name: string) => values?.[name] == null ? match : String(values[name]));
}

